export function normalizeLocale(value: string | null | undefined): AppLocale {
  const candidate = (value ?? DEFAULT_LOCALE).toLowerCase();
  return SUPPORTED_LOCALES.includes(candidate as AppLocale)
    ? (candidate as AppLocale)
    : DEFAULT_LOCALE;
}

export function getText(
  locale: AppLocale,
  key: TranslationKey,
  params?: TranslationParams,
): string {
  const template = translationMap[locale][key] ?? translationMap[DEFAULT_LOCALE][key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
